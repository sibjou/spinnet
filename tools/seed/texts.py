def feminize(surname: str) -> str:
    """Иванов → Иванова, Бельский → Бельская."""
    for tail, repl in (("ский", "ская"), ("цкий", "цкая"), ("ов", "ова"), ("ев", "ева"), ("ёв", "ёва"),
                       ("ин", "ина"), ("ын", "ына")):
        if surname.endswith(tail):
            return surname[: -len(tail)] + repl
    return surname


